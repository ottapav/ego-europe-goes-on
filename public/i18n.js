  function make(lang, K) {
    const L = DICT[lang] ? lang : 'en';
    const d = DICT[L];
    const fill = (s, p = {}) => (typeof s === 'function' ? s(p) : String(s).replace(/\{(\w+)\}/g, (_, k) => (p[k] != null ? p[k] : '')));
    const t = (key, p) => fill(d[key] ?? DICT.en[key] ?? key, p);
    const num = v => {
      const r = Math.round(v * 10) / 10;
      return L === 'cs' ? String(r).replace('.', ',') : String(r);
    };
    const signed = v => (v > 0 ? '+' : v < 0 ? '−' : '') + num(Math.abs(v));
    const cs = L === 'cs' ? CS : null;
    const card = id => K.CARDS.find(c => c.id === id);

    const name = {
      state: id => cs?.states[id]?.name ?? K.STATES[id]?.name ?? id,
      goal: id => cs?.goals[id]?.name ?? K.GOALS[id]?.name ?? id,
      threat: id => cs?.threats[id]?.name ?? K.THREATS[id]?.name ?? id,
      rival: id => cs?.rivals[id]?.name ?? K.RIVALS[id]?.name ?? id,
      partner: id => cs?.partners[id]?.name ?? K.PARTNERS[id]?.name ?? id,
      level: i => cs?.levels[i] ?? K.LEVELS[i],
      proposal: id => cs?.proposals[id]?.name ?? K.PROPOSALS.find(p => p.id === id)?.name ?? id,
      card: id => {
        const c = card(id);
        if (!c) return id;
        if (c.goalCard) return t('card.contribute', { goal: name.goal(c.goalCard) });
        if (c.rejoin) return t('card.rejoin', { goal: name.goal(c.rejoin) });
        return cs?.cards[id]?.[0] ?? c.name;
      },
    };
    const text = {
      state: (id, f) => cs?.states[id]?.[f] ?? (f === 'ruleName' ? K.STATES[id].rule.name : f === 'ruleText' ? K.STATES[id].rule.text
        : ['population', 'gdp', 'defence', 'line'].includes(f) ? K.STATES[id].facts[f] : K.STATES[id][f]),
      goal: (id, f) => cs?.goals[id]?.[f] ?? K.GOALS[id][f],
      threat: (id, f) => cs?.threats[id]?.[f] ?? K.THREATS[id][f],
      proposal: (id, f) => cs?.proposals[id]?.[f] ?? K.PROPOSALS.find(p => p.id === id)?.[f],
      cardNote: id => {
        const c = card(id);
        if (c.goalCard) return text.goal(c.goalCard, 'note');
        if (c.rejoin) return t('card.rejoinNote');
        return cs?.cards[id]?.[1] ?? c.note ?? '';
      },
      fact: i => cs?.facts[i] ?? K.EU_FACTS[i],
      event: ev => {
        if (!ev) return null;
        let n, x;
        if (ev.kind === 'crisis') { n = cs?.crises[ev.id]?.name ?? K.CRISES[ev.id].name; x = cs?.crises[ev.id]?.text ?? K.CRISES[ev.id].text; }
        else if (ev.id === 'braindrain') { n = cs?.events.braindrain.name ?? 'Brain drain to the USA'; x = cs?.events.braindrain.text ?? 'States with Education under 45 lose Education −4 and Tech −2.'; }
        else { const e = K.NEUTRAL_EVENTS.find(e => e.id === ev.id) || {}; n = cs?.events[ev.id]?.name ?? e.name; x = cs?.events[ev.id]?.text ?? e.text; }
        return { name: ev.severe ? t('event.severe', { name: n }) : n, text: x };
      },
      ending: e => {
        if (e.id === 'rival') return { name: t(`ending.rival.${e.rival}`), text: t('ending.rival.text', { rival: name.rival(e.rival) }) };
        return { name: t(`ending.${e.id}`), text: t(`ending.${e.id}.text`, { n: e.goalsDone }) };
      },
    };
    // Turn a structured message from the engine ({ k, ...params }) into a sentence.
    function msg(m) {
      if (!m) return '';
      if (typeof m === 'string') return m;
      const p = { ...m };
      if (m.card) p.card = name.card(m.card);
      if (m.goal) p.goal = name.goal(m.goal);
      if (m.state) p.state = name.state(m.state);
      if (m.level != null) p.level = name.level(m.level);
      if (m.rival) p.rival = name.rival(m.rival);
      if (m.lock) p.lock = msg(m.lock);
      switch (m.k) {
        case 'news.goal': return t('news.goal', { ...p, icon: K.GOALS[m.goal].icon, late: m.late ? t('news.goalLate') : '' });
        case 'news.council': return t('news.council', { name: name.proposal(m.proposal), result: t(m.passed ? 'news.councilPassed' : 'news.councilRejected'), rule: t(m.rule === 'QMV' ? 'rule.qmv' : 'rule.unanimity') });
        case 'news.level': return t('news.level', { level: L === 'cs' ? name.level(m.level).toLowerCase() : name.level(m.level) });
        case 'news.deadline': return m.rival ? t('news.deadline', p) : t('news.deadlineWar', p);
        case 'news.event': return t('news.event', { name: text.event(m.event).name });
        case 'news.over': return t('news.over', { name: text.ending(m.ending).name });
        default: return t(m.k, p);
      }
    }
    return { lang: L, t, num, signed, name, text, msg };
  }

  const api = { make, langs: ['en', 'cs'], DICT, CS };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.EGO_I18N = api;
